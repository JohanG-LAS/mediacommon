func FuzzAnnexBUnmarshal(f *testing.F) {
	for _, ca := range casesAnnexB {
		f.Add(ca.encin)
	}

	f.Fuzz(func(t *testing.T, b []byte) {
		var au AnnexB
		err := au.Unmarshal(b)
		if err != nil {
			return
		}

		require.NotZero(t, len(au))

		for _, nalu := range au {
			require.NotZero(t, len(nalu))
		}

		_, err = au.Marshal()
		require.NoError(t, err)
	})
}
